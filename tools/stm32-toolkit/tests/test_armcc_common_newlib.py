"""Bounded ``build.newlibSpecs`` schema, identity, and template evidence.

The optional field exists only for the reviewed no-semihosting pragma.  These
tests prove that absent and empty values keep the historical model identity
and generated bytes, that a non-empty value changes identity, that the schema
stays closed, and that managed/native link options emit the spec exactly once.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from stm32_toolkit.generation.managed_files import model_sha256_for
from stm32_toolkit.project_model import ProjectManifestError, load_project_model

from test_generation import (
    EXPECTED_CMAKE,
    plan_for,
    standard_payload,
    write_project,
)

REPO_ROOT = Path(__file__).resolve().parents[3]


def _payload(specs, *, native: bool = False, schema_version: int = 3) -> dict:
    payload = standard_payload()
    payload["schemaVersion"] = schema_version
    if native:
        payload["generation"]["nativeLinkerScript"] = "STM32F429_FLASH.ld"
    if specs is not None:
        payload["build"]["newlibSpecs"] = specs
    return payload


def _render(root: Path, name: str = "CMakeLists.txt") -> bytes:
    return next(entry.after_bytes for entry in plan_for(root).files if entry.path == name)


def test_absent_and_empty_newlib_specs_keep_identity_and_bytes(tmp_path):
    absent = write_project(tmp_path / "absent", _payload(None))
    empty = write_project(tmp_path / "empty", _payload([]))

    absent_model = load_project_model(absent)
    empty_model = load_project_model(empty)
    assert absent_model.build.newlib_specs == ()
    assert empty_model.build.newlib_specs == ()
    assert model_sha256_for(absent_model) == model_sha256_for(empty_model)
    assert _render(absent) == _render(empty) == EXPECTED_CMAKE.encode("utf-8")
    assert plan_for(absent).managed_manifest_bytes == plan_for(empty).managed_manifest_bytes


def test_nonempty_newlib_specs_changes_model_and_configuration_identity(tmp_path):
    absent = write_project(tmp_path / "absent", _payload(None))
    nosys = write_project(tmp_path / "nosys", _payload(["nosys.specs"]))

    absent_model = load_project_model(absent)
    nosys_model = load_project_model(nosys)
    assert nosys_model.build.newlib_specs == ("nosys.specs",)
    assert model_sha256_for(absent_model) != model_sha256_for(nosys_model)

    absent_plan = plan_for(absent)
    nosys_plan = plan_for(nosys)
    assert absent_plan.model_sha256 != nosys_plan.model_sha256
    assert absent_plan.plan_id != nosys_plan.plan_id
    assert absent_plan.managed_manifest_bytes != nosys_plan.managed_manifest_bytes

    cmake = _render(nosys).decode("utf-8")
    assert cmake.count('"--specs=nosys.specs"') == 1
    assert '"--specs=nano.specs"' not in cmake


def test_native_template_keeps_default_specs_and_never_duplicates(tmp_path):
    absent = write_project(
        tmp_path / "native-absent", _payload(None, native=True)
    )
    nosys = write_project(
        tmp_path / "native-nosys", _payload(["nosys.specs"], native=True)
    )
    for root in (absent, nosys):
        (root / "STM32F429_FLASH.ld").write_bytes(b"MEMORY {}\n")

    absent_cmake = _render(absent).decode("utf-8")
    nosys_cmake = _render(nosys).decode("utf-8")
    assert absent_cmake == nosys_cmake
    assert nosys_cmake.count('"--specs=nano.specs"') == 1
    assert nosys_cmake.count('"--specs=nosys.specs"') == 1


@pytest.mark.parametrize(
    "specs",
    [
        ["nosys.specs", "nosys.specs"],
        ["nano.specs"],
        [1],
    ],
)
def test_schema_rejects_duplicate_unknown_and_non_string_specs(tmp_path, specs):
    root = write_project(tmp_path / "invalid", _payload(specs))
    with pytest.raises(ProjectManifestError) as caught:
        load_project_model(root)
    assert "build.newlibSpecs" in str(caught.value.details.get("field", ""))


def test_root_and_packaged_schema_copies_match():
    root_schema = REPO_ROOT / "schemas" / "stm32-project.schema.json"
    packaged_schema = (
        REPO_ROOT
        / "tools"
        / "stm32-toolkit"
        / "src"
        / "stm32_toolkit"
        / "schemas"
        / "stm32-project.schema.json"
    )
    assert root_schema.read_bytes() == packaged_schema.read_bytes()
